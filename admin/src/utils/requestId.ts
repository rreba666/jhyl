/**
 * 请求幂等键工具（后台侧，独立实现，**不与 mini_shop 互相 import**）。
 *
 * ⚠️ 与留痕台账**查询**用的 `requestId` 筛选参数（`/api/admin/ledger*?requestId=...`）**无关**：
 * 那是筛选条件，本文件生成的是**请求头 `X-Request-Id`** 的值。
 *
 * 用途：后端「接口调用计数」积木（`fengling-apicount`）每成功调一次接口计数 +1，
 * **幂等键就是请求头 `X-Request-Id`** —— 同一个 id 重复提交只算一次调用、只落一条留痕。
 * 后台管理端只在**写操作**（如手动对账）上使用：
 *   1. 一次业务动作只生成一次 id，连点复用同一个值；
 *   2. **失败后重试复用同一个 id**（否则后端会把重试当成新调用，重复计数 / 重复留痕）；
 *   3. 成功后丢弃该 id，下一次动作重新生成。
 *
 * 不传该请求头 = **无幂等**（保持历史行为），由调用方决定是否使用。
 */

/** 同一毫秒内的自增序号（模块级变量，仅用于降低碰撞概率）。 */
let seq = 0

/**
 * 生成一个请求级唯一 id：`时间戳36进制 + '-' + 随机串`（不引入 UUID 库）。
 * 额外拼一个自增序号，保证**同一毫秒内连续生成**也不会重复（例如快速连点两下）。
 */
export function createRequestId(): string {
  // 毫秒时间戳转 36 进制：长度短且整体递增
  const time = Date.now().toString(36)
  // 进程内自增序号：同毫秒内多次生成也能区分
  seq = (seq + 1) % 1296 // 36^2，回绕后仍由随机串兜底
  // 两段随机串：避免不同浏览器/标签页之间碰撞
  const random = Math.random().toString(36).slice(2, 10) + Math.random().toString(36).slice(2, 6)
  return `${time}-${seq.toString(36).padStart(2, '0')}${random}`
}
