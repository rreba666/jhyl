/**
 * 请求幂等键工具（`X-Request-Id` 请求头）。
 *
 * ⚠️ 与请求体里配送任务自己的 `requestId` 字段**无关**，本文件只负责生成请求头 `X-Request-Id` 的值。
 *
 * 用途：后端「接口调用计数」积木（`fengling-apicount`）每成功调一次接口计数 +1，
 * **幂等键就是请求头 `X-Request-Id`** —— 同一个 id 重复提交只算一次调用、只落一条留痕。
 *
 * 因此调用方的正确用法是：
 *   1. **防连点**：一次业务动作（如「秒退」一笔订单）只生成一次 id，动作期间连点复用同一个值；
 *   2. **失败重试**：网络抖动 / 超时后重试**必须复用同一个 id**，否则重试会被后端当成一次全新的调用而重复计数；
 *   3. **成功后清空**：动作成功后丢弃该 id，下一次动作重新生成（那是新的一次调用，应该重新计数）。
 *
 * 不传 `X-Request-Id` = **无幂等**（保持历史行为）：重试会被当成多次调用，只在确实需要幂等的写操作上使用。
 */

/**
 * 生成一个请求级唯一 id：`时间戳36进制 + '-' + 随机串`（不引入 UUID 库，小程序体积友好）。
 * 形态示例：`m1k2j3a4-7f3c9q2x` —— 前半段随时间递增，排查日志时能直接看出先后顺序。
 */
export function createRequestId(): string {
  // 毫秒时间戳转 36 进制：长度短且整体递增
  const time = Date.now().toString(36)
  // 两段随机串：单段随机在小程序环境碰撞概率偏高，拼两段更稳（36^8 ≈ 2.8 万亿种）
  const random = Math.random().toString(36).slice(2, 10) + Math.random().toString(36).slice(2, 6)
  return `${time}-${random}`
}
